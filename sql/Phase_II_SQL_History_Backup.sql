INSERT INTO FLIGHT_PERFORMANCE
(PERFORMANCE_ID, SCHEDULE_ID, ACTUAL_DEPARTURE_TIME,
 FLIGHT_STATUS, DELAY_MINUTES)
SELECT
    ROW_NUMBER() OVER (
        ORDER BY d.FLIGHT_DATE, d.FLIGHT, d.SCHEDULED
    ),
    s.SCHEDULE_ID,
    CASE
        WHEN d.ACTUAL_DEPARTURE IS NOT NULL
        THEN TO_TIMESTAMP(
            TO_CHAR(d.FLIGHT_DATE, 'DD-MON-YYYY') || ' ' ||
            d.ACTUAL_DEPARTURE,
            'DD-MON-YYYY HH:MI AM'
        )
        ELSE NULL
    END,
    d.FLIGHT_STATUS,
    NVL(d.DELAYED_MINUTES, 0)
FROM RWA_FLIGHT_DATA d
JOIN FLIGHT f
    ON d.FLIGHT = f.FLIGHT_NUMBER
JOIN FLIGHT_SCHEDULE s
    ON s.FLIGHT_ID = f.FLIGHT_ID
   AND s.FLIGHT_DATE = d.FLIGHT_DATE
   AND s.SCHEDULED_DEPARTURE_TIME =
       TO_TIMESTAMP(
           TO_CHAR(d.FLIGHT_DATE, 'DD-MON-YYYY') || ' ' ||
           d.SCHEDULED,
           'DD-MON-YYYY HH:MI AM'
       );

COMMIT;

