INSERT INTO FLIGHT_PERFORMANCE
(PERFORMANCE_ID, SCHEDULE_ID, ACTUAL_DEPARTURE_TIME,
 FLIGHT_STATUS, DELAY_MINUTES)
SELECT
    s.SCHEDULE_ID,
    s.SCHEDULE_ID,
    CASE
        WHEN d.ACTUAL_DEPARTURE IS NOT NULL
        THEN TO_TIMESTAMP(
            TO_CHAR(d.FLIGHT_DATE, 'DD-MON-YYYY')
            || ' ' || d.ACTUAL_DEPARTURE,
            'DD-MON-YYYY HH:MI AM'
        )
        ELSE NULL
    END,
    d.FLIGHT_STATUS,
    d.DELAYED_MINUTES
FROM RWA_FLIGHT_DATA d
JOIN FLIGHT_SCHEDULE s
ON d.FLIGHT_DATE = s.FLIGHT_DATE
AND d.FLIGHT = (
    SELECT f.FLIGHT_NUMBER
    FROM FLIGHT f
    WHERE f.FLIGHT_ID = s.FLIGHT_ID
);

