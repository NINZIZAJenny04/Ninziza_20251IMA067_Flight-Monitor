CREATE TABLE FLIGHT (
    FLIGHT_ID NUMBER PRIMARY KEY,
    FLIGHT_NUMBER VARCHAR2(20) NOT NULL,
    ORIGIN VARCHAR2(50) NOT NULL,
    DESTINATION VARCHAR2(50) NOT NULL
);

CREATE TABLE FLIGHT_SCHEDULE (
    SCHEDULE_ID NUMBER PRIMARY KEY,
    FLIGHT_ID NUMBER NOT NULL,
    FLIGHT_DATE DATE NOT NULL,
    SCHEDULED_DEPARTURE_TIME TIMESTAMP NOT NULL,
    CONSTRAINT FK_FLIGHT_SCHEDULE
        FOREIGN KEY (FLIGHT_ID)
        REFERENCES FLIGHT(FLIGHT_ID)
);

CREATE TABLE FLIGHT_PERFORMANCE (
    PERFORMANCE_ID NUMBER PRIMARY KEY,
    SCHEDULE_ID NUMBER NOT NULL,
    ACTUAL_DEPARTURE_TIME TIMESTAMP,
    FLIGHT_STATUS VARCHAR2(20) NOT NULL,
    DELAY_MINUTES NUMBER DEFAULT 0,
    CONSTRAINT FK_FLIGHT_PERFORMANCE
        FOREIGN KEY (SCHEDULE_ID)
        REFERENCES FLIGHT_SCHEDULE(SCHEDULE_ID)
);

